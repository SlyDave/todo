#!/usr/bin/env node
// Regenerates every derived copy of the agent configuration from the canonical
// `.cursor/` tree: the `.claude/` compatibility mirrors and the `.cursor-plugin/`
// bundle. Run after editing anything under `.cursor/`.
//
//   node .sdlc/scripts/sync-distributions.mjs [--check]
//
// With --check it exits non-zero if any derived copy is stale, which is what CI
// should run.

import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync
} from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const checkOnly = process.argv.includes('--check')

const GENERATED_NOTICE =
  'This directory is generated by .sdlc/scripts/sync-distributions.mjs.\n' +
  'Edit the canonical files under .cursor/ instead; changes here are overwritten.\n'

// The plugin bundle deliberately omits hooks. Hook commands are resolved relative
// to the project root, so the scripts under .cursor/hooks/ only exist in a repo
// created from this template. Shipping hooks.json in a plugin would point at
// files the host repo does not have, and hooks fail open by default, so the
// failure would be silent.
const PLUGIN_PARTS = ['agents', 'rules', 'skills', 'commands']
const CLAUDE_PARTS = ['agents', 'skills']

function copyTree(from, to) {
  if (!existsSync(from)) return false
  rmSync(to, { recursive: true, force: true })
  cpSync(from, to, { recursive: true })
  return true
}

function snapshot(dir) {
  if (!existsSync(dir)) return null
  const entries = []
  const walk = (current, prefix) => {
    for (const name of readdirSync(current).sort()) {
      const full = join(current, name)
      const rel = prefix ? `${prefix}/${name}` : name
      if (statSync(full).isDirectory()) walk(full, rel)
      else entries.push(`${rel}\u0000${readFileSync(full, 'utf8')}`)
    }
  }
  walk(dir, '')
  return entries.join('\u0001')
}

function sync() {
  const written = []

  for (const part of CLAUDE_PARTS) {
    if (copyTree(join(repoRoot, '.cursor', part), join(repoRoot, '.claude', part))) {
      written.push(`.claude/${part}`)
    }
  }
  mkdirSync(join(repoRoot, '.claude'), { recursive: true })
  writeFileSync(join(repoRoot, '.claude', 'README.md'), `# .claude\n\n${GENERATED_NOTICE}`)

  const pluginDir = join(repoRoot, '.cursor-plugin')
  for (const part of PLUGIN_PARTS) {
    if (copyTree(join(repoRoot, '.cursor', part), join(pluginDir, part))) {
      written.push(`.cursor-plugin/${part}`)
    }
  }

  const mcpSource = join(repoRoot, '.cursor', 'mcp.json')
  if (existsSync(mcpSource)) {
    mkdirSync(pluginDir, { recursive: true })
    writeFileSync(join(pluginDir, 'mcp.json'), readFileSync(mcpSource, 'utf8'))
    written.push('.cursor-plugin/mcp.json')
  }

  const pkg = JSON.parse(readFileSync(join(repoRoot, '.sdlc', 'template.json'), 'utf8'))
  writeFileSync(
    join(pluginDir, 'plugin.json'),
    `${JSON.stringify(
      {
        name: pkg.name,
        version: pkg.version,
        description: pkg.description,
        author: pkg.author
      },
      null,
      2
    )}\n`
  )
  writeFileSync(join(pluginDir, 'README.md'), `# ${pkg.name} plugin\n\n${GENERATED_NOTICE}`)

  return written
}

if (checkOnly) {
  const before = [
    ...CLAUDE_PARTS.map((p) => join(repoRoot, '.claude', p)),
    join(repoRoot, '.cursor-plugin')
  ].map(snapshot)
  sync()
  const after = [
    ...CLAUDE_PARTS.map((p) => join(repoRoot, '.claude', p)),
    join(repoRoot, '.cursor-plugin')
  ].map(snapshot)
  const stale = before.some((value, index) => value !== after[index])
  if (stale) {
    console.error(
      'Derived distributions were stale. Run: node .sdlc/scripts/sync-distributions.mjs'
    )
    process.exit(1)
  }
  console.log('Distributions are up to date.')
} else {
  const written = sync()
  console.log(`Synced ${written.length} derived path(s) from .cursor/:`)
  for (const path of written) console.log(`  ${path}`)
}
